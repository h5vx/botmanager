// Package raftcluster implements leadership and replicated state for
// botmanager via an embedded Raft cluster:
//
//   - несколько узлов, один master и остальные replica; только master
//     держит процессы ботов и общается с Telegram (см. internal/botlifecycle);
//   - через Raft реплицируются команды на создание/изменение ботов,
//     запись сообщений и статусов доставки, принятые обновления Telegram и
//     реестр узлов (см. Command);
//   - хранилище — встроенное (BoltDB) как конечный автомат Raft (FSM), со
//     снимками (raft.FileSnapshotStore).
//
// # Публичный API
//
// Open(Config) (*Node, error) поднимает (или перезапускает) один узел.
// Дальше используется только Node:
//
//   - Apply(Command, timeout) (*ApplyResult, error) — применить команду;
//     успешно только на лидере (ErrNotLeader иначе);
//   - IsLeader() bool, Subscribe() (<-chan bool, cancel) — проверить/
//     подписаться на смену лидерства этого узла;
//   - SubscribeApplied() (<-chan struct{}, cancel) — подписка "что-то
//     применилось, перечитай состояние", без деталей команды;
//   - ListBots/GetBot/GetMessage/ListMessages/ReadJournal/ListNodes —
//     чтение реплицированного состояния, работает на любом узле;
//   - AddVoter/RemoveServer/TransferLeadershipTo — состав кластера и
//     лидерство (только на лидере).
//
// internal/botlifecycle строится поверх этого API, не заглядывая в
// raft.Raft напрямую; реализация BotAdmin/Messaging/Maintenance
// (internal/rpcserver) — тоже тонкий адаптер поверх Node.
//
// # Формат команд FSM
//
// Command (command.go) — размеченное объединение (по полю Type) команд:
// CreateBot/UpdateBot/SetBotState/DeleteBot для ботов, PutMessage/
// UpdateDelivery для истории сообщений и статусов доставки.
// JSON-кодируется в raft.Log.Data. Все значения, которые могли бы
// различаться между репликами — время, идентификаторы — обязаны быть
// решены вызывающей стороной *до* Apply и лежат внутри команды: FSM.Apply
// не вызывает time.Now() и не генерирует ID (см. подробный комментарий на
// Command в command.go) — это то, что делает применение детерминированным
// и воспроизводимым при переигрывании журнала на новом лидере.
//
// # Идемпотентность записи сообщений
//
// PutMessageCommand.IdempotencyKey уникален по всему кластеру. Повторное
// применение команды с уже известным ключом — no-op, возвращающий
// существующее сообщение без изменений (не ошибка). Это отражает то, что
// вызывающая сторона вызывает Send с идемпотентным ключом и не обязан знать, был ли
// этот конкретный RPC первым или повторным.
//
// # Retention истории сообщений — по числу записей на бота
//
// Журнал сообщений реплицируется через Raft и живёт в памяти каждого узла
// (плюс попадает в каждый снимок), поэтому неограниченный рост
// недопустим — это упирается в память и размер снимков, а не в диск.
// Обрезка — **по числу записей**, не по времени: храним последние N
// сообщений на бота, N задаётся конфигурацией
// (`raft.message_retention_per_bot`, DefaultMessageRetentionPerBot = 500
// по умолчанию).
//
// Почему 500: сообщение в среднем — десятки-сотни байт (текст уведомления
// плюс служебные поля), 500 записей на бота — это порядка сотни-другой
// килобайт на бота даже с запасом. При реалистичном числе ботов
// (единицы-десятки) суммарный объём остаётся мегабайтами, а не сотнями
// мегабайт — снимок Raft остаётся дешёвым, и встроенное хранилище не
// требует внешней базы.
//
// Обрезка реализована как **детерминированная функция применяемых
// команд**, а не фоновый процесс: FSM.applyPutMessage добавляет новую
// запись и сразу же (в том же вызове Apply) обрезает лишнее с начала
// списка данного бота (fsm_messages.go, trimRetention) — иначе реплики
// могли бы разойтись, обрезая в разное время или в разном порядке.
// Обратная сторона: если сообщение вытеснено retention, повторное
// применение PutMessage с тем же (уже вытесненным) idempotency_key создаёт
// новую запись, а не считается дублем — на практике ключи не переиспользу-
// ются (собираются из смысла сообщения), так что это не проблема.
//
// # Snapshot/Restore
//
// FSM.Snapshot() берёт согласованную копию состояния под RLock (боты +
// сообщения каждого бота, с сохранением порядка) и кодирует её в JSON;
// FSM.Restore() полностью заменяет состояние декодированной копией. Порядок
// сообщений внутри бота (важен для ListMessages/для итогового round-trip)
// хранится явно списком, а не выводится из map.
//
// # Журнал событий (journal.go)
//
// Всё, что видит подписчик Messaging.Subscribe, — часть реплицированного
// состояния: FSM.Apply дописывает JournalEntry для каждого изменения,
// интересного подписчику (принятые обновления Telegram, статусы доставки,
// смена состояния бота), с номером Seq из счётчика, который сам входит в
// состояние. Поэтому номер события одинаков на всех узлах, и подписку можно
// возобновить на любом узле с нужного места. Журнал ограничен по числу
// записей (DefaultJournalRetention) тем же доводом, что и история
// сообщений.
//
// Обновления Telegram записываются вместе с offset'ом getUpdates
// (RecordUpdatesCommand): раннер подтверждает их Telegram только после
// коммита, новый лидер продолжает с реплицированного offset'а, а
// обновления ниже уже записанного offset'а отбрасываются как дубли.
//
// # Кластер
//
// Config.Bootstrap с пустым BootstrapPeers бутстрапит кластер из этого
// узла и KnownPeers (статическая конфигурация, одинаковая на всех
// узлах); узел без bootstrap ждёт, пока лидер добавит его через AddVoter.
// Реестр узлов (nodes.go) хранит gRPC-адреса членов кластера — по ним
// rpcserver пересылает записи лидеру и проверяет доступность соседей.
// Лидер при каждом избрании регистрирует себя и KnownPeers.
//
// Транспорт — TCP или, с Config.TLS, mutual TLS (transport.go): каждое
// соединение между узлами шифруется, обе стороны предъявляют сертификаты
// общего CA.
//
// Dependencies позволяет подменить транспорт и хранилища in-memory
// реализациями (raft.NewInmemTransport и т.д.) — так устроены многоузловые
// тесты (node_test.go, node_security_test.go), а node_security_test.go
// дополнительно поднимает настоящий двухузловой кластер поверх mTLS.
//
// # Шифрование токенов (tokencipher.go)
//
// С Config.TokenCipher токены ботов шифруются AES-256-GCM в Node.Apply,
// до попадания в журнал Raft, и расшифровываются в Node.GetBot/ListBots.
// В BoltDB, снимках, экспорте состояния и трафике между узлами токен
// никогда не лежит открытым текстом. Значения без префикса шифрования
// читаются как есть, поэтому ключ можно ввести на работающем кластере.
